export const FISHING_TARGETS = [
  "Любой хищник",
  "Щука",
  "Судак",
  "Окунь",
  "Жерех",
  "Голавль",
  "Сом",
  "Другая рыба",
] as const;
export const FISHING_TIMES = ["Утро", "День", "Вечер", "Ночь"] as const;
export type AdviceInput = { location: string; target: string; time: string; notes: string };
export type FishingPlan = {
  source: "rules";
  input: AdviceInput;
  sections: { title: string; text: string }[];
};
const clean = (value: string, max: number) =>
  value
    .replace(/./gs, (character) => {
      const code = character.charCodeAt(0);
      return code < 32 || code === 127 ? " " : character;
    })
    .trim()
    .slice(0, max);

export function prepareAdviceInput(input: AdviceInput): AdviceInput {
  return {
    location: clean(input.location, 140),
    target: FISHING_TARGETS.find((value) => value === input.target) ?? FISHING_TARGETS[0],
    time: FISHING_TIMES.find((value) => value === input.time) ?? FISHING_TIMES[0],
    notes: clean(input.notes, 400),
  };
}
