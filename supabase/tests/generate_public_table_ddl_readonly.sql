-- ZAPRUDA: generate stage-1 public TABLE DDL from live catalog (READ ONLY).
-- Output is SQL text for OFFLINE review; this query itself changes NOTHING.
-- NOT a complete restore: constraints, indexes, functions, policies, grants,
-- auth hooks, bucket metadata and extensions must be supplied in later phases.
-- Run on PROD only as a SELECT. Never execute generated lines automatically.
WITH relations AS (
 SELECT c.oid,c.relname,c.relkind FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
 WHERE n.nspname='public' AND c.relkind IN ('r','p')
), columns AS (
 SELECT r.oid,r.relname,a.attnum,
        format('%I %s%s%s%s',
          a.attname,
          format_type(a.atttypid,a.atttypmod),
          CASE WHEN a.attcollation<>t.typcollation AND a.attcollation<>0
               THEN ' COLLATE '||a.attcollation::regcollation::text ELSE '' END,
          CASE WHEN a.attgenerated='s' THEN ' GENERATED ALWAYS AS ('||pg_get_expr(ad.adbin,ad.adrelid)||') STORED'
               WHEN a.attidentity='a' THEN ' GENERATED ALWAYS AS IDENTITY'
               WHEN a.attidentity='d' THEN ' GENERATED BY DEFAULT AS IDENTITY'
               WHEN ad.adbin IS NOT NULL THEN ' DEFAULT '||pg_get_expr(ad.adbin,ad.adrelid)
               ELSE '' END,
          CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END) AS definition
 FROM relations r JOIN pg_attribute a ON a.attrelid=r.oid AND a.attnum>0 AND NOT a.attisdropped
 JOIN pg_type t ON t.oid=a.atttypid
 LEFT JOIN pg_attrdef ad ON ad.adrelid=a.attrelid AND ad.adnum=a.attnum
), table_sql AS (
 SELECT r.relname,r.relkind,
        format('CREATE TABLE public.%I (\n%s\n);',
               r.relname,string_agg('  '||col.definition, E',\n' ORDER BY col.attnum)) AS ddl
 FROM relations r JOIN columns col ON col.oid=r.oid
 GROUP BY r.relname,r.relkind
)
SELECT 'table' AS object_type,relname AS object_name,ddl,
       CASE WHEN relkind='p' THEN 'PARTITIONED TABLE: MANUAL REVIEW REQUIRED'
            WHEN ddl ~* '\\mnextval\\s*\\(' THEN 'SEQUENCE DEPENDENCY: MANUAL REVIEW REQUIRED'
            ELSE 'REVIEW REQUIRED' END AS warning
FROM table_sql ORDER BY relname;
-- Caveats: inheritance/partition specification, sequences, explicit storage
-- parameters, policies, privileges, constraints, owned identities and triggers
-- are NOT reconstructed. Defaults can refer to sequences/functions not yet present.
